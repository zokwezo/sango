func TonelessFromHeightless() map[string]string { return lexiconRowsAndCols.tonelessFromHeightless }

type DictRowsMap = map[string]DictRows
type DictRows = []DictRow

// The canonical format is strictly more general, but
// the entries in LexiconRows.Canonical exactly match the regular expression
// `^([-]?[hbvydzqgHpfltsKkwBVYDZQGnPmr][aAeEiIoOxcuU][_:^]){1,5}$`
// where the mapping from Canonical to Lemma is:
//
// h -> (unaspirated h is omitted)
// H -> h (aspirated h is preserved)
// B -> mb
// q -> gb
// Q -> ngb
// D -> nd
// G -> ng
// K -> kp
// P -> mp
// V -> mv
// Y -> ny
// Z -> nz
// A -> añ
// x -> ɛ (open e)
// E -> eñ
// I -> iñ
// c -> ɔ (open o)
// o -> o
// O -> oñ
// u -> u
// U -> uñ
// _ -> low  tone (omitted)
// : -> mid  tone (dieresis   diacritic)
// ^ -> high tone (circumflex diacritic)
//
// All other symbols (e.g. k) are the same in Canonical and Lemma.

type DictRow struct {
	Toneless           string // = Heightless, but with pitch removed
	Heightless         string // = Lemma, but with whitespace, case, and height removed
	Lemma              string
	Canonical          string // = Lemma, but ASCII encoded
	UDPos              string
	UDFeature          string
	Category           string
	Frequency          int
	EnglishTranslation string
	EnglishDefinition  string
}

type DictCols struct {
	Bytes              []byte
	Runes              []rune
	Toneless           [][]byte
	Heightless         [][]byte
	LemmaRunes         [][]rune
	LemmaUTF8          [][]byte
	Canonical          [][]byte
	UDPos              [][]byte
	UDFeature          [][]byte
	Category           [][]byte
	Frequency          []int
	EnglishTranslation [][]byte
	EnglishDefinition  [][]byte
}

type DictRowRegexp struct {
	TonelessRE           *regexp.Regexp
	HeightlessRE         *regexp.Regexp
	LemmaRE              *regexp.Regexp
	CanonicalRE          *regexp.Regexp
	UDPosRE              *regexp.Regexp
	UDFeatureRE          *regexp.Regexp
	CategoryRE           *regexp.Regexp
	EnglishTranslationRE *regexp.Regexp
	EnglishDefinitionRE  *regexp.Regexp
	FrequencyMin         int
	FrequencyMax         int
}

func Lookup(dictRows DictRows, dictRowRegexp DictRowRegexp) DictRows {
	return lookupMatchingRows(dictRows, dictRowRegexp)
}

//////////////////////////////////////////////////////////////////////////////
// IMPLEMENTATION

func lookupMatchingRows(in DictRows, f DictRowRegexp) DictRows {
	var out DictRows
	for _, r := range in {
		if r.Toneless != "" &&
			(f.FrequencyMin == 0 || f.FrequencyMin <= r.Frequency) &&
			(f.FrequencyMax == 0 || f.FrequencyMax > r.Frequency) &&
			(f.TonelessRE == nil || f.TonelessRE.MatchString(r.Toneless)) &&
			(f.HeightlessRE == nil || f.HeightlessRE.MatchString(r.Heightless)) &&
			(f.LemmaRE == nil || f.LemmaRE.MatchString(r.Lemma)) &&
			(f.CanonicalRE == nil || f.CanonicalRE.MatchString(r.Canonical)) &&
			(f.UDPosRE == nil || f.UDPosRE.MatchString(r.UDPos)) &&
			(f.UDFeatureRE == nil || f.UDFeatureRE.MatchString(r.UDFeature)) &&
			(f.CategoryRE == nil || f.CategoryRE.MatchString(r.Category)) &&
			(f.EnglishTranslationRE == nil || f.EnglishTranslationRE.MatchString(r.EnglishTranslation)) &&
			(f.EnglishDefinitionRE == nil || f.EnglishDefinitionRE.MatchString(r.EnglishDefinition)) {
			out = append(out, r)
		}
	}
	return out
}

